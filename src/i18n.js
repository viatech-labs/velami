  const MESSAGES = { en, it, ru };

  function browserLanguages() {
    if (typeof navigator === 'undefined') return [];
    return navigator.languages && navigator.languages.length ? navigator.languages : [navigator.language || ''];
  }

  function resolve(pref) {
    if (SUPPORTED.includes(pref)) return pref;
    for (const l of browserLanguages()) {
      const base = String(l).toLowerCase().split('-')[0];
      if (SUPPORTED.includes(base)) return base;
    }
    return 'en';
  }

  let lang = resolve();

  function t(key, params) {
    let s = MESSAGES[lang][key];
    if (s == null) s = en[key];
    if (s == null) return key;
    if (params) s = s.replace(/\{(\w+)\}/g, (m, k) => (params[k] != null ? String(params[k]) : m));
    return s;
  }

  const label = (type) => t('type.' + type) === 'type.' + type ? type : t('type.' + type);

  function apply(root) {
    if (!root || !root.querySelectorAll) return;
    for (const n of root.querySelectorAll('[data-i18n]')) {
      const key = n.getAttribute('data-i18n');
      if (key.endsWith('_html')) n.innerHTML = t(key); else n.textContent = t(key);
    }
    for (const n of root.querySelectorAll('[data-i18n-ph]')) n.setAttribute('placeholder', t(n.getAttribute('data-i18n-ph')));
    for (const n of root.querySelectorAll('[data-i18n-title]')) n.setAttribute('title', t(n.getAttribute('data-i18n-title')));
    if (root.documentElement) root.documentElement.lang = lang;
  }

  return {
    SUPPORTED,
    MESSAGES,
    t,
    label,
    apply,
    resolve,
    setLanguage(pref) { lang = resolve(pref); return lang; },
    get lang() { return lang; },
  };
